const NAV_ITEMS = [
  { to: '/dashboard', icon: <IconDashboard />, label: 'Dashboard' },
  { to: '/invoices',  icon: <IconInvoices />,  label: 'Invoices'  },
  { to: '/expenses',  icon: <IconExpenses />,  label: 'Expenses'  },
  { to: '/insights',  icon: <IconInsights />,  label: 'AI Insights' },
  { to: '/settings',  icon: <IconSettings />,  label: 'Settings'  },
];

export default function Sidebar({ isOpen, onClose }) {
  const { user, logout } = useAuth();
  const navigate = useNavigate();

  const handleLogout = async () => {
    await logout();
    navigate('/login');
  };

  return (
    <>
      {/* Mobile overlay */}
      {isOpen && <div className="sidebar-overlay" onClick={onClose} />}

      <aside className={`sidebar ${isOpen ? 'open' : ''}`}>
        {/* Logo */}
        <div className="sidebar-logo">
          <div className="logo-mark">
            <div className="logo-icon">EX</div>
            <div className="logo-text">
              <span className="logo-name">Expenza</span>
              <span className="logo-sub">Finance Manager</span>
            </div>
          </div>
        </div>

        {/* Navigation */}
        <nav className="sidebar-nav">
          <div className="nav-section">
            <div className="nav-section-label">Main Menu</div>
            {NAV_ITEMS.map(({ to, icon, label }) => (
              <NavLink
                key={to}
                to={to}
                className={({ isActive }) => `nav-link ${isActive ? 'active' : ''}`}
                onClick={onClose}
              >
                <span className="nav-icon icon-svg">{icon}</span>
                {label}
              </NavLink>
            ))}
          </div>
        </nav>

        {/* User Footer */}
        <div className="sidebar-footer">
          <div className="user-card">
            <div className="avatar">{user?.initials || user?.name?.[0]?.toUpperCase() || 'U'}</div>
            <div className="user-info">
              <div className="user-name">{user?.name || 'User'}</div>
              <div className="user-email">{user?.email || ''}</div>
            </div>
            <button className="logout-btn" onClick={handleLogout} title="Logout">
              <IconLogout />
            </button>
          </div>
        </div>
      </aside>
    </>
  );
}
